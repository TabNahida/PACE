#!/usr/bin/env python3
"""Generate the C++ named module interfaces in modules/ from modules/exports.json.

    python3 scripts/generate_modules.py          # rewrite modules/*.cppm
    python3 scripts/generate_modules.py --check  # exit 1 if a file is out of date

Every module re-exports the names of the modules it depends on instead of importing them. GCC 16
rejects a module that includes PACE headers in its global module fragment and also imports another
PACE module built from the same headers (duplicate template instantiations mangle twice), so no PACE
module imports another one; only modules/pace.cppm, which includes nothing, imports them all.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "modules" / "exports.json"

GUARD = """#if defined(__GNUC__) && !defined(__clang__) && __GNUC__ < 16
#error PACE_named_modules_require_Clang_or_GCC_16_with_coroutine_module_fixes
#endif"""


def closure(modules, name):
    """The module and everything it depends on, dependencies first, each once."""
    ordered = []

    def visit(current):
        for dependency in modules[current]["deps"]:
            visit(dependency)
        if current not in ordered:
            ordered.append(current)

    visit(name)
    return ordered


def namespace_of(entry):
    qualified = entry.get("name") or entry["alias"]
    return qualified.rsplit("::", 1)[0]


def declaration(entry):
    if "alias" in entry:
        return f"namespace {entry['alias'].rsplit('::', 1)[1]} = {entry['target']};"
    return f"using ::{entry['name']};"


def body_for(modules, name):
    """Export blocks for `name` and its dependencies, grouped by guard and namespace."""
    groups = []  # (guards tuple, namespace, [declarations])
    for module in closure(modules, name):
        feature = modules[module]["feature"]
        for entry in modules[module]["exports"]:
            # A namespace alias is a declaration attached to its module, not a re-exportable name: only
            # the module that owns it exports it.
            if "alias" in entry and module != name:
                continue
            guards = tuple(g for g in (feature, entry.get("requires")) if g)
            namespace = namespace_of(entry)
            if groups and groups[-1][0] == guards and groups[-1][1] == namespace:
                groups[-1][2].append(declaration(entry))
            else:
                groups.append((guards, namespace, [declaration(entry)]))
    text = []
    for guards, namespace, declarations in groups:
        block = f"export namespace {namespace}\n{{\n" + "\n".join(declarations) + f"\n}} // namespace {namespace}\n"
        if guards:
            condition = " && ".join(f"defined({guard})" for guard in guards)
            block = f"#if {condition}\n{block}#endif\n"
        text.append(block)
    return "\n".join(text)


def module_file(modules, name):
    headers = sorted(f"#include <pace/{modules[module]['header']}>" for module in closure(modules, name))
    return f"""// Generated by scripts/generate_modules.py from modules/exports.json. Do not edit.
// ABI-preserving facade: declarations belong to the global module, just as they do for #include
// consumers. A module whose library is disabled still exists and exports nothing from that library.
module;
{GUARD}
{chr(10).join(headers)}

export module pace.{name};

{body_for(modules, name)}"""


def aggregate_file(modules):
    imports = "\n".join(f"export import pace.{name};" for name in modules)
    return f"""// Generated by scripts/generate_modules.py from modules/exports.json. Do not edit.
// Every PACE module. `import pace;` matches `#include <pace/pace.hpp>`; import one module, such as
// `import pace.net;`, to depend on less.
module;
{GUARD}

export module pace;

{imports}
"""


def outputs():
    modules = json.loads(SPEC.read_text())["modules"]
    files = {ROOT / "modules" / f"{name}.cppm": module_file(modules, name) for name in modules}
    files[ROOT / "modules" / "pace.cppm"] = aggregate_file(modules)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report out-of-date files instead of writing them")
    arguments = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        if path.is_file() and path.read_text() == text:
            continue
        if arguments.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(text)
    if stale:
        print("Out of date (run: python3 scripts/generate_modules.py):", *stale, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
